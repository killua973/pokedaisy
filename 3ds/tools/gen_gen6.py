def chart():
    rows = []
    for atk in TYPES:
        row = [CHART.get((atk, dfn), 2) for dfn in TYPES]
        rows.append(row)
    return rows


def render():
    rows = chart()
    out = ["// Generated by 3ds/tools/gen_gen6.py - the Gen 6 type chart, do not edit.",
           "// Cells: 0 immune, 1 not very, 2 neutral, 4 super effective. Rows attack, columns defend.",
           "#include \"pd_gen6.h\"", "",
           "const uint8_t pd_gen6_type_chart[PD_GEN6_TYPE_COUNT][PD_GEN6_TYPE_COUNT] = {"]
    for atk, row in zip(TYPES, rows):
        out.append("    { %s }, // %s attacks" % (", ".join(str(c) for c in row), atk.title()))
    out.append("};")
    out.append("")
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        with open(OUT, "r", encoding="utf-8") as f:
            if f.read() != text:
                raise SystemExit("pd_gen6_gen.c is stale: run python3 3ds/tools/gen_gen6.py")
        print("pd_gen6_gen.c up to date")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
